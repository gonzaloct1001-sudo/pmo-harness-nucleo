"""Autoría limpia de los documentos entregables (Word, Excel, PowerPoint, PDF y Markdown de salida).

Los documentos que entrega el harness deben verse como elaborados por el usuario de la sesión: sin rastros
técnicos (librerías, plantillas genéricas, metadatos heredados) ni textuales (menciones al proceso de
generación, marcadores internos, caracteres invisibles). Este módulo reúne:

- cargar_autoria(raiz_proyecto): autor, organización y listas de términos desde proyecto.yaml (bloque autoria).
- normalizar_texto(texto): quita caracteres invisibles y reemplaza caracteres tipográficos atípicos.
- limpiar_ooxml(ruta, autor, titulo, organizacion): reescribe propiedades y elimina partes heredadas de un
  .docx/.xlsx/.pptx (miniatura, customXml, comentarios) y fija el modo de compatibilidad actual de Word.
- revisar_archivo(ruta, cfg): lista de hallazgos (errores y advertencias) para verificar_autoria.py.

Integridad: si las bases de un concurso exigen declarar el uso de herramientas de IA, eso es un requisito que
se informa al usuario (matriz de cumplimiento). Este módulo nunca redacta ni oculta declaraciones.
"""
import re
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from xml.sax.saxutils import escape

try:
    import yaml
except ImportError:  # el harness siempre instala pyyaml; esto solo evita caer al importar
    yaml = None

# --- Caracteres ---------------------------------------------------------------------------------------------
# Los de ancho cero y el guion blando no se ven al leer y son el rastro típico de texto copiado de otra herramienta:
# se tratan como error. Los espacios especiales y el signo menos tipográfico son legítimos en documentos de
# terceros (PDF, LaTeX): se normalizan con --corregir en lo propio, pero solo generan advertencia.
ANCHO_CERO = re.compile("[\u200b\u200c\u200d\u2060\ufeff\u00ad]")
INVISIBLES = {
    "\u200b": "", "\u200c": "", "\u200d": "", "\u2060": "", "\ufeff": "", "\u00ad": "",  # ancho cero, guion blando
    "\u2212": "-", "\u2011": "-", "\u2010": "-",                                            # menos y guiones atípicos
    "\u202f": " ", "\u2007": " ", "\u2009": " ", "\u200a": " ", "\u00a0": " ",             # espacios especiales
}
RE_INVISIBLES = re.compile("[" + "".join(INVISIBLES) + "]")


def normalizar_texto(texto: str) -> str:
    return RE_INVISIBLES.sub(lambda m: INVISIBLES[m.group(0)], texto)


def contar_invisibles(texto: str) -> int:
    return len(RE_INVISIBLES.findall(texto))


# --- Términos -----------------------------------------------------------------------------------------------
# Errores: rastros inequívocos del proceso (restos de conversación con un asistente, marcadores y rutas internas
# del harness, nombres de librerías). Nunca son contenido legítimo de un entregable.
TERMINOS_ERROR = [
    r"como (un |una )?(modelo de lenguaje|asistente( virtual)?|IA|inteligencia artificial)\b",
    r"\b(aqu[íi] tienes|claro, aqu[íi]|por supuesto, aqu[íi]|espero que (esto|te) (te )?sirva)\b",
    r"\bmi (fecha de corte|conocimiento (llega|est[áa] actualizado) hasta)\b",
    r"generad[oa]s? por (una |un )?(IA|inteligencia artificial|asistente)\b",
    r"\bPMO Harness\b", r"Co-Authored-By",
    r"\[PENDIENTE", r"<!--", r"registro-de-alta", r"hechos\.md", r"avance-alta", r"_entrada/", r"_procesado",
    r"\.claude/", r"herramientas/\w+\.py", r"\bmd_a_docx\b", r"\bpython-docx\b", r"\bopenpyxl\b", r"\bpython-pptx\b",
]
# Advertencias: pueden ser legítimas (el tema del proyecto, un nombre propio, un término técnico). Se revisan
# caso a caso y se eximen con autoria.terminos_permitidos.
TERMINOS_ADVERTENCIA = [
    r"\bClaude\b", r"\bAnthropic\b", r"\bChat\s?GPT\b", r"\bOpenAI\b", r"\bGPT-?\d", r"\bCopilot\b", r"\bGemini\b",
    r"\bLLM\b", r"modelos? de lenguaje", r"asistente (de |virtual de )?(IA|inteligencia artificial)",
    r"generad[oa]s? autom[aá]ticamente", r"\bharness\b",
    r"\bIA\b", r"inteligencia artificial", r"\bF\d{3}\b", r"\bPRUEBA\b",
]
SENSIBLE_A_MAYUSCULAS = {r"\bIA\b", r"\bPRUEBA\b"}
# Metadatos que delatan la herramienta de generación.
META_PROHIBIDA = re.compile(r"python-docx|openpyxl|python-pptx|reportlab|pypdf|generated by|claude|anthropic|chatgpt|"
                            r"openai|\bgpt\b|\bIA\b|\bAI\b|harness", re.I)
SKILLS_DIR = Path(__file__).resolve().parent.parent / ".claude" / "skills"


def nombres_skills():
    if not SKILLS_DIR.exists():
        return []
    return [p.name for p in SKILLS_DIR.iterdir() if p.is_dir() and "-" in p.name]


def cargar_autoria(raiz_proyecto=None) -> dict:
    """Bloque `autoria` de proyecto.yaml con valores por defecto razonables."""
    cfg = {}
    if raiz_proyecto and yaml:
        archivo = Path(raiz_proyecto) / "proyecto.yaml"
        if archivo.exists():
            try:
                import _config
                cfg = _config.cargar(raiz_proyecto)
            except ImportError:
                cfg = yaml.safe_load(archivo.read_text(encoding="utf-8")) or {}
    aut = dict(cfg.get("autoria") or {})
    resp = cfg.get("responsable") or {}

    def limpio(v):
        v = str(v or "").strip()
        return "" if "PENDIENTE" in v.upper() else v

    aut["nombre"] = limpio(aut.get("nombre")) or limpio(resp.get("nombre"))
    aut["organizacion"] = limpio(aut.get("organizacion"))
    aut["terminos_prohibidos"] = list(aut.get("terminos_prohibidos") or [])
    aut["terminos_permitidos"] = [str(x).lower() for x in (aut.get("terminos_permitidos") or [])]
    aut["excluir"] = [str(x) for x in (aut.get("excluir") or [])]
    return aut


def excluido(ruta, aut):
    """Archivos que no se verifican ni se corrigen: documentos de terceros (cartas de socios, certificados) y
    declaraciones que las bases exigen (por ejemplo, la declaración de uso de herramientas de IA)."""
    from fnmatch import fnmatch
    nombre, completo = Path(ruta).name, Path(ruta).as_posix()
    return any(fnmatch(nombre, p) or fnmatch(completo, p) or fnmatch(completo, "*/" + p.lstrip("/")) for p in aut.get("excluir") or [])


# --- Limpieza de paquetes Office (OOXML) ----------------------------------------------------------------------
APLICACION = {".docx": "word", ".docm": "word", ".xlsx": "xl", ".xlsm": "xl", ".pptx": "ppt", ".pptm": "ppt"}
PARTES_TEXTO = re.compile(r"^(word/(document|header\d*|footer\d*|footnotes|endnotes)\.xml|xl/sharedStrings\.xml|"
                          r"xl/worksheets/sheet\d+\.xml|ppt/slides/slide\d+\.xml|ppt/notesSlides/notesSlide\d+\.xml)$")


def _core_xml(autor, titulo, ahora):
    t = f"<dc:title>{escape(titulo)}</dc:title>" if titulo else ""
    a = escape(autor or "")
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" '
            'xmlns:dcmitype="http://purl.org/dc/dcmitype/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
            f'{t}<dc:creator>{a}</dc:creator><cp:lastModifiedBy>{a}</cp:lastModifiedBy><cp:revision>1</cp:revision>'
            f'<dcterms:created xsi:type="dcterms:W3CDTF">{ahora}</dcterms:created>'
            f'<dcterms:modified xsi:type="dcterms:W3CDTF">{ahora}</dcterms:modified></cp:coreProperties>')


def _app_xml(organizacion):
    empresa = f"<Company>{escape(organizacion)}</Company>" if organizacion else ""
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" '
            'xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">'
            f'<DocSecurity>0</DocSecurity>{empresa}</Properties>')


def _sin_relacion(xml, patron_destino):
    return re.sub(r'<Relationship\b[^>]*Target="' + patron_destino + r'"[^>]*/>', "", xml)


def limpiar_ooxml(ruta, autor="", titulo="", organizacion=""):
    """Reescribe el paquete en su lugar. Devuelve la lista de cambios aplicados."""
    ruta = Path(ruta)
    if ruta.suffix.lower() not in APLICACION:
        return []
    cambios = []
    ahora = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    with zipfile.ZipFile(ruta) as z:
        entradas = [(i, z.read(i.filename)) for i in z.infolist()]
    salida = []
    for info, datos in entradas:
        nombre = info.filename
        if nombre.startswith("customXml/") or re.match(r"docProps/thumbnail\.\w+$", nombre) \
                or nombre in ("word/comments.xml", "word/commentsExtended.xml", "word/commentsIds.xml", "word/people.xml"):
            cambios.append(f"eliminada parte heredada {nombre}")
            continue
        if nombre == "docProps/core.xml":
            datos = _core_xml(autor, titulo, ahora).encode("utf-8")
            cambios.append("propiedades del documento reescritas")
        elif nombre == "docProps/app.xml":
            datos = _app_xml(organizacion).encode("utf-8")
        elif nombre == "docProps/custom.xml":
            cambios.append("eliminadas propiedades personalizadas")
            continue
        elif nombre == "[Content_Types].xml":
            xml = datos.decode("utf-8")
            xml = re.sub(r'<Override\b[^>]*PartName="/(customXml/[^"]*|docProps/thumbnail\.\w+|docProps/custom\.xml|'
                         r'word/comments\w*\.xml|word/commentsIds\.xml|word/people\.xml)"[^>]*/>', "", xml)
            datos = xml.encode("utf-8")
        elif nombre.endswith(".rels"):
            xml = datos.decode("utf-8")
            xml = _sin_relacion(xml, r"[^\"]*customXml/[^\"]*")
            xml = _sin_relacion(xml, r"[^\"]*docProps/thumbnail\.\w+")
            xml = _sin_relacion(xml, r"[^\"]*docProps/custom\.xml")
            xml = _sin_relacion(xml, r"(comments\w*|commentsIds|people)\.xml")
            datos = xml.encode("utf-8")
        elif nombre == "word/settings.xml":
            xml = datos.decode("utf-8")
            nuevo = re.sub(r'(w:name="compatibilityMode"[^>]*w:val=")\d+(")', r"\g<1>15\g<2>", xml)
            if nuevo != xml:
                cambios.append("modo de compatibilidad de Word actualizado")
            datos = nuevo.encode("utf-8")
        elif PARTES_TEXTO.match(nombre):
            xml = datos.decode("utf-8")
            n = contar_invisibles(xml)
            if n:
                cambios.append(f"{n} carácter(es) invisible(s) o atípico(s) normalizados en {nombre}")
                datos = normalizar_texto(xml).encode("utf-8")
        salida.append((info, datos))
    tmp = ruta.with_suffix(ruta.suffix + ".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for info, datos in salida:
            z.writestr(info, datos)
    tmp.replace(ruta)
    return cambios


# --- Revisión -------------------------------------------------------------------------------------------------
def _texto_ooxml(ruta):
    """Texto visible de un .docx/.xlsx/.pptx sin depender de sus librerías (lee el XML)."""
    partes = []
    with zipfile.ZipFile(ruta) as z:
        for nombre in z.namelist():
            if PARTES_TEXTO.match(nombre):
                xml = z.read(nombre).decode("utf-8", errors="replace")
                partes.append(re.sub(r"<[^>]+>", " ", re.sub(r"</w:p>|</a:p>|</si>", "\n", xml)))
    return re.sub(r"[ \t]+", " ", "\n".join(partes))


def _meta_ooxml(ruta):
    meta, partes, extra = {}, [], []
    with zipfile.ZipFile(ruta) as z:
        partes = z.namelist()
        if "docProps/core.xml" in partes:
            core = z.read("docProps/core.xml").decode("utf-8", errors="replace")
            for campo in ("creator", "lastModifiedBy", "description", "keywords", "subject", "category", "title", "created"):
                m = re.search(r"<[\w]+:" + campo + r"\b[^>]*>(.*?)</[\w]+:" + campo + ">", core, re.S)
                meta[campo] = (m.group(1).strip() if m else "")
        if "docProps/app.xml" in partes:
            app = z.read("docProps/app.xml").decode("utf-8", errors="replace")
            m = re.search(r"<Application>(.*?)</Application>", app)
            meta["application"] = m.group(1) if m else ""
            m = re.search(r"<Template>(.*?)</Template>", app)
            meta["template"] = m.group(1) if m else ""
        if "word/settings.xml" in partes:
            s = z.read("word/settings.xml").decode("utf-8", errors="replace")
            m = re.search(r'w:name="compatibilityMode"[^>]*w:val="(\d+)"', s)
            meta["compat"] = m.group(1) if m else ""
        if "word/document.xml" in partes:
            d = z.read("word/document.xml").decode("utf-8", errors="replace")
            if re.search(r"<w:(ins|del)\b", d):
                extra.append("el documento tiene control de cambios sin aceptar")
            if "<w:vanish/>" in d:
                extra.append("el documento tiene texto oculto")
    return meta, partes, extra


def _texto_pdf(ruta):
    try:
        from pypdf import PdfReader
    except ImportError:
        return "", {}
    r = PdfReader(str(ruta))
    meta = {k.strip("/").lower(): str(v) for k, v in (r.metadata or {}).items()}
    return "\n".join((p.extract_text() or "") for p in r.pages), meta


def revisar_texto(texto, aut, origen=""):
    errores, advert = [], []
    permitidos = aut.get("terminos_permitidos") or []
    patrones_error = TERMINOS_ERROR + [re.escape(str(x)) for x in aut.get("terminos_prohibidos") or []]
    patrones_adv = TERMINOS_ADVERTENCIA + [r"\b" + re.escape(s) + r"\b" for s in nombres_skills()]
    for lista, destino in ((patrones_error, errores), (patrones_adv, advert)):
        for patron in lista:
            for m in re.finditer(patron, texto, 0 if patron in SENSIBLE_A_MAYUSCULAS else re.I):
                if m.group(0).lower() in permitidos:
                    continue
                ini = max(0, m.start() - 40)
                contexto = texto[ini:m.end() + 40].replace("\n", " ").strip()
                destino.append(f"{origen}término «{m.group(0)}»: …{contexto}…")
                break
    n0 = len(ANCHO_CERO.findall(texto))
    if n0:
        errores.append(f"{origen}{n0} carácter(es) invisible(s) de ancho cero o guion blando (rastro de texto copiado)")
    n = contar_invisibles(texto) - n0
    if n:
        advert.append(f"{origen}{n} espacio(s) especial(es) o signo(s) menos tipográfico(s): normalízalos si el documento es tuyo")
    rayas = texto.count("—")
    if texto and rayas / max(len(texto), 1) * 1000 > 3 and rayas >= 5:
        advert.append(f"{origen}uso frecuente de la raya «—» ({rayas} veces): revisar el estilo de puntuación")
    return errores, advert


def revisar_archivo(ruta, aut=None):
    """Devuelve (errores, advertencias) de un archivo entregable."""
    ruta = Path(ruta)
    aut = aut or cargar_autoria(None)
    errores, advert = [], []
    ext = ruta.suffix.lower()
    if excluido(ruta, aut):
        return [], [f"{ruta.name}: excluido de la verificación (autoria.excluir: documento de terceros o declaración exigida)"]
    permitidos = aut.get("terminos_permitidos") or []
    m = re.search(r"harness|_procesado|avance-alta|registro-de-alta", ruta.name, re.I)
    if m and m.group(0).lower() not in permitidos:
        errores.append(f"nombre de archivo delata el proceso: {ruta.name}")
    m = re.search(r"claude|chatgpt|openai|gemini|copilot", ruta.name, re.I)
    if m and m.group(0).lower() not in permitidos:
        advert.append(f"nombre de archivo menciona «{m.group(0)}»: {ruta.name}")
    if re.search(r"prueba|borrador", ruta.name, re.I):
        advert.append(f"nombre de archivo con «prueba» o «borrador»: {ruta.name}")
    if ext in APLICACION:
        meta, partes, extra = _meta_ooxml(ruta)
        for campo in ("creator", "lastModifiedBy", "description", "keywords", "subject", "category", "application", "template"):
            valor = meta.get(campo, "")
            if valor and META_PROHIBIDA.search(valor):
                errores.append(f"propiedad «{campo}» delata la herramienta: {valor}")
        if meta.get("description"):
            advert.append(f"propiedad «comentarios» no vacía: {meta['description']}")
        if "macintosh" in (meta.get("application") or "").lower():
            errores.append(f"propiedad «aplicación» heredada de una plantilla: {meta['application']}")
        creado = meta.get("created", "")[:4]
        if creado.isdigit() and int(creado) < datetime.now().year - 1:
            advert.append(f"fecha de creación antigua ({meta.get('created')}): si el archivo es tuyo, probablemente es heredada "
                          "de una plantilla (--corregir la actualiza); si es de un tercero, exclúyelo con autoria.excluir")
        if aut.get("nombre") and meta.get("creator") and meta["creator"] != aut["nombre"]:
            advert.append(f"autor del documento «{meta['creator']}» distinto del configurado «{aut['nombre']}»")
        if not meta.get("creator"):
            advert.append("el documento no tiene autor en sus propiedades")
        if meta.get("compat") and int(meta["compat"]) < 15:
            advert.append("Word lo abrirá en «Modo de compatibilidad» (versión antigua del formato)")
        for p in partes:
            if p.startswith("customXml/") or re.match(r"docProps/thumbnail\.", p):
                errores.append(f"parte heredada de plantilla: {p}")
            if p in ("word/comments.xml", "docProps/custom.xml"):
                errores.append(f"contiene {p} (comentarios o propiedades personalizadas)")
        errores += extra
        e, a = revisar_texto(_texto_ooxml(ruta), aut)
    elif ext == ".pdf":
        texto, meta = _texto_pdf(ruta)
        for k in ("producer", "creator", "author", "subject", "keywords"):
            if meta.get(k) and META_PROHIBIDA.search(meta[k]):
                errores.append(f"metadato PDF «{k}» delata la herramienta: {meta[k]}")
        e, a = revisar_texto(texto, aut)
    elif ext in (".md", ".txt", ".csv", ".html"):
        e, a = revisar_texto(ruta.read_text(encoding="utf-8", errors="replace"), aut)
    else:
        return errores, advert + [f"formato {ext or 'sin extensión'} no revisado"]
    return errores + e, advert + a
